// types.ts — типы данных для ArticlesSection (страница /blog)

/** Статья блога */
export interface Article {
    /** Уникальный идентификатор статьи */
    id: string;
    /** Категория статьи ("УК", "Жители", "Аналитика") */
    category: string;
    /** Заголовок статьи */
    title: string;
    /** Краткое описание (2–3 строки) */
    excerpt: string;
    /** Дата публикации в виде строки */
    date: string;
    /** Примерное время чтения */
    readTime: string;
    /**
     * CSS-градиент для превью-изображения.
     * Используется вместо реальных картинок как заглушка.
     */
    imageGradient: string;
}
